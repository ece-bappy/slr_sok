"""Score each core paper against the evaluation checklist (paper OUTLINE.md section 8.2, Table 11 / Figure 12).

Usage: python scripts/checklist_scores.py
Reads review/synthesis/papers.csv (the verified, adjudicated coding) and writes
review/synthesis/checklist.csv (paper x item: yes / no / unknown / not_coded) and checklist.md.

Item -> coded field (only items the existing coding supports are scored):
  C1 temporal or cross-dataset split   split_protocols contains temporal or cross_dataset
  C2 validation-only thresholds        NOT CODED (needs new coding)
  C3 FPR or PR-AUC reported            metrics contain fpr or pr_auc (the "stated base rate" part is
                                       NOT CODED; the score is an upper bound for the full item)
  C4 origin / environment probe        shortcut_check contains probe
  C5 labels independent of features    label_feature_overlap: no -> yes; yes -> no; unclear -> unknown;
                                       not_applicable -> unknown
  C6 per-TLS-version results           NOT CODED (tls_versions_stated is about the data, not results)
  C7 end-to-end cost                   cost_reported = end_to_end
  C8 data released                     data_released = yes (captures, labels or features; the
                                       coding does not separate pcaps from features)
"""
import csv
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SYN = ROOT / "review" / "synthesis"

ITEMS = [
    ("C1", "Temporal or cross-dataset split"),
    ("C2", "Validation-only thresholds"),
    ("C3", "FPR or PR-AUC reported"),
    ("C4", "Origin / environment probe"),
    ("C5", "Labels independent of features"),
    ("C6", "Per-TLS-version results"),
    ("C7", "End-to-end cost"),
    ("C8", "Data released"),
]


def vals(s):
    return {t.strip() for t in s.split(";") if t.strip()}


def score(p):
    lfo = p["label_feature_overlap"].strip()
    return {
        "C1": "yes" if vals(p["split_protocols"]) & {"temporal", "cross_dataset"} else "no",
        "C2": "not_coded",
        "C3": "yes" if vals(p["metrics"]) & {"fpr", "pr_auc"} else "no",
        "C4": "yes" if "probe" in vals(p["shortcut_check"]) else "no",
        "C5": {"no": "yes", "yes": "no"}.get(lfo, "unknown"),
        "C6": "not_coded",
        "C7": "yes" if p["cost_reported"].strip() == "end_to_end" else "no",
        "C8": "yes" if p["data_released"].strip() == "yes" else "no",
    }


def main():
    with open(SYN / "papers.csv", encoding="utf-8-sig", newline="") as f:
        papers = list(csv.DictReader(f))
    rows = []
    for p in papers:
        s = score(p)
        scored = [k for k, v in s.items() if v in ("yes", "no")]
        rows.append({"paper_id": p["paper_id"], "year": p["year"], **s,
                     "met": sum(s[k] == "yes" for k in scored), "scored_items": len(scored)})
    with open(SYN / "checklist.csv", "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    n = len(rows)
    L = ["# Evaluation checklist: core-set compliance (generated by `scripts/checklist_scores.py`)", "",
         f"{n} core papers, from the verified and adjudicated coding (`papers.csv`). "
         "Items C2 and C6 are not in the coding scheme and are not scored.", "",
         "| Item | yes | no | unknown | not coded |", "|---|---|---|---|---|"]
    for k, name in ITEMS:
        c = Counter(r[k] for r in rows)
        L.append(f"| {k} {name} | {c['yes']} ({c['yes'] / n:.0%}) | {c['no']} | {c['unknown']} | {c['not_coded']} |")
    met = Counter(r["met"] for r in rows)
    L += ["", "Papers by number of the 6 scored items met:", "",
          "| Items met | Papers |", "|---|---|"]
    L += [f"| {k} | {met[k]} |" for k in range(0, 7)]
    L += ["", "Notes:",
          "- C3 counts any FPR or PR-AUC; whether a base rate is stated is not coded, so this is an upper bound.",
          "- C5 'unknown' = label_feature_overlap unclear or not_applicable.",
          "- C8 counts released captures, labels or features; the coding does not separate pcaps."]
    (SYN / "checklist.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
