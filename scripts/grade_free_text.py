"""Merge the human free-text grades (todo/01_free_text_grading.csv) into
review/coding/ensemble_validation.csv and write review/coding/validation_report.md.

Grades: correct / partial / wrong / empty; invented: yes / no (rules in
todo/01_free_text_grading_RULES.md).
"""
import csv
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GRADES = ROOT / "todo" / "01_free_text_grading.csv"
VALID = ROOT / "review" / "coding" / "ensemble_validation.csv"
REPORT = ROOT / "review" / "coding" / "validation_report.md"
MODELS = ("flash_lite", "gemini38")
NEW_COLS = ["grade_flash_lite", "grade_gemini38",
            "invented_flash_lite", "invented_gemini38", "grade_note"]


def read(path):
    with open(path, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def main():
    grades = {(g["paper_id"], g["field"]): g for g in read(GRADES)}
    rows = read(VALID)
    fields = list(rows[0].keys())
    fields += [c for c in NEW_COLS if c not in fields]

    used = set()
    for r in rows:
        g = grades.get((r["paper_id"], r["field"]))
        if r["kind"] != "free_text":
            continue
        if g is None:
            raise SystemExit(f"no grade for {r['paper_id']} {r['field']}")
        for m in MODELS:
            gr, inv = g[f"grade_{m}"].strip(), g[f"invented_{m}"].strip()
            if gr not in {"correct", "partial", "wrong", "empty"} or inv not in {"yes", "no"}:
                raise SystemExit(f"bad grade in {r['paper_id']} {r['field']} {m}: {gr!r}/{inv!r}")
            r[f"grade_{m}"], r[f"invented_{m}"] = gr, inv
        r["grade_note"] = g["note"].strip()
        r["outcome"] = "graded by hand"
        used.add((r["paper_id"], r["field"]))
    missing = set(grades) - used
    if missing:
        raise SystemExit(f"graded rows not in validation sheet: {sorted(missing)}")

    with open(VALID, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)

    ft = [r for r in rows if r["kind"] == "free_text"]
    sc = Counter(r["outcome"] for r in rows if r["kind"] == "scored")
    n = len(ft)
    lines = ["# Extraction validation (4 blind papers: S2338, S1938, S1163, S2008)", "",
             "Generated by `scripts/grade_free_text.py` from `review/coding/ensemble_validation.csv`.", "",
             "## Scored fields (automatic, ensemble of Flash Lite + Gemini 3.8)", "",
             "| Outcome | Rows |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in sorted(sc.items())]
    agreed = sc.get("agreed_correct", 0) + sc.get("agreed_WRONG", 0)
    lines += ["", f"Agreed rows correct: {sc.get('agreed_correct', 0)}/{agreed}. Disputed rows go to the human.", "",
              f"## Free-text fields ({n} rows, graded by hand per todo/01 rules)", "",
              "| Model | correct | partial | wrong | empty | invented |", "|---|---|---|---|---|---|"]
    for m in MODELS:
        c = Counter(r[f"grade_{m}"] for r in ft)
        inv = sum(r[f"invented_{m}"] == "yes" for r in ft)
        lines.append(f"| {m} | {c['correct']}/{n} | {c['partial']} | {c['wrong']} | {c['empty']} | {inv} |")
    lines += ["", "By field (correct / n):", "", "| Field | " + " | ".join(MODELS) + " |", "|---|---|---|"]
    for fld in sorted({r["field"] for r in ft}):
        sub = [r for r in ft if r["field"] == fld]
        lines.append(f"| {fld} | " + " | ".join(
            f"{sum(r[f'grade_{m}'] == 'correct' for r in sub)}/{len(sub)}" for m in MODELS) + " |")
    hw = [r for r in ft if r["grade_note"].lower().startswith("human value wrong")]
    lines += ["", f"Human reference judged wrong by the grader: {len(hw)} row(s)."]
    lines += [f"- {r['paper_id']} {r['field']}: {r['grade_note']}" for r in hw]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(REPORT.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
