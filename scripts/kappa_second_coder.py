"""Inter-rater reliability: second coder (14 core papers, blind) vs the verified coding.

Usage: python scripts/kappa_second_coder.py
Reads review/coding/second_coder_14_papers.csv and review/coding/core_67_papers_verification.csv
(verified_value is coder 1). Writes review/coding/kappa_report.md and
review/coding/second_coder_disagreements.csv (for adjudication by coder 1, paper open).

- single-choice fields: Cohen's kappa per field, plus kappa pooled over all of them
  (labels prefixed by field so categories never collide);
- list fields: every allowed option is a yes/no decision per paper; kappa over those
  decisions, plus the share of papers with exactly the same set;
- free-text fields: no kappa; listed for a human same-meaning judgement.
"""
import csv
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
D = ROOT / "review" / "coding"

SINGLE = ["label_feature_overlap", "cert_fields_read", "ech_considered", "main_split", "easy_vs_hard_reported",
          "granularity", "cost_reported", "code_released", "data_released", "first_n_packets"]
LISTS = {
    "label_source": ["sandbox", "blocklist_cert", "blocklist_ja3", "ids_alerts", "dataset_provided", "manual",
                     "generated", "other"],
    "feature_groups": ["G1", "G2", "G3", "G4", "G5"],
    "fingerprints_used": ["none", "JA3", "JA3S", "JA4", "JA4S", "other"],
    "tls_versions_stated": ["1.0", "1.1", "1.2", "1.3", "not_stated"],
    "split_protocols": ["random", "stratified_random", "per_packet", "host_grouped", "temporal", "cross_dataset",
                        "not_applicable"],
    "shortcut_check": ["none", "identifier_removal", "ablation", "probe", "other"],
}
FREE = ["datasets_evaluated", "features_used", "model_family", "metrics", "hardware"]


def clean(v: str) -> str:
    v = (v or "").split("{", 1)[0]  # verified values sometimes carry a trailing structured dump
    return re.sub(r"\s+", " ", v).strip().strip(";, ").lower()


def single(field: str, v: str) -> str:
    v = clean(v)
    if field == "first_n_packets":
        return "whole flow" if (not v or "whole" in v) else re.sub(r"[^0-9]", "", v) or v
    return v or "(blank)"


def items(field: str, v: str) -> set:
    opts = {o.lower(): o for o in LISTS[field]}
    return {opts[t.strip()] for t in re.split(r"[;,|]", clean(v)) if t.strip() in opts}


def kappa(pairs: list) -> float:
    n = len(pairs)
    if not n:
        return float("nan")
    po = sum(a == b for a, b in pairs) / n
    ca, cb = Counter(a for a, _ in pairs), Counter(b for _, b in pairs)
    pe = sum(ca[k] * cb[k] for k in ca) / n / n
    return 1.0 if pe == 1 else (po - pe) / (1 - pe)


def main() -> None:
    sec = [r for r in csv.DictReader(open(D / "second_coder_14_papers.csv", encoding="utf-8-sig"))
           if r["paper_id"] != "(format only)"]
    ver = {(r["paper_id"], r["field"]): r for r in csv.DictReader(
        open(D / "core_67_papers_verification.csv", encoding="utf-8-sig"))}
    by_field = {}
    for r in sec:
        by_field.setdefault(r["field"], []).append((r, ver[(r["paper_id"], r["field"])]))
    papers = sorted({r["paper_id"] for r in sec})

    lines = [f"# Second-coder reliability ({len(papers)} core papers, blind)", "",
             "Coder 1 = verified coding (`core_67_papers_verification.csv`); coder 2 = colleague "
             "(`second_coder_14_papers.csv`). Generated by `scripts/kappa_second_coder.py`.", "",
             "## Single-choice fields", "", "| Field | n | Agreement | Cohen's κ |", "|---|---|---|---|"]
    # Pooling single-choice fields with field-prefixed labels would make chance agreement tiny and push
    # kappa towards raw agreement, so report the mean and median of the per-field kappas instead.
    disagree, ks, n_agree, n_all = [], [], 0, 0
    for f in SINGLE:
        pairs = [(single(f, v["verified_value"]), single(f, s["your_value"])) for s, v in by_field[f]]
        agree = sum(a == b for a, b in pairs)
        n_agree, n_all = n_agree + agree, n_all + len(pairs)
        ks.append(kappa(pairs))
        lines.append(f"| {f} | {len(pairs)} | {agree}/{len(pairs)} | {ks[-1]:.2f} |")
        disagree += [(f, s, v, "single") for (s, v), (a, b) in zip(by_field[f], pairs) if a != b]
    # The rulebook lets "certificate info not used" be either no or not_applicable; both give the same
    # visibility tier, so also report the field with the two merged.
    merged = [(a.replace("not_applicable", "no"), b.replace("not_applicable", "no")) for a, b in
              [(single("cert_fields_read", v["verified_value"]), single("cert_fields_read", s["your_value"]))
               for s, v in by_field["cert_fields_read"]]]
    lines.append(f"| cert_fields_read, no ≡ not_applicable | {len(merged)} | "
                 f"{sum(a == b for a, b in merged)}/{len(merged)} | {kappa(merged):.2f} |")
    ks_sorted = sorted(ks)
    median = (ks_sorted[4] + ks_sorted[5]) / 2
    lines += [f"| **all single-choice** | {n_all} | {n_agree}/{n_all} ({n_agree / n_all:.0%}) | "
              f"mean {sum(ks) / len(ks):.2f}, median {median:.2f} |", "",
              "## List fields (one yes/no decision per allowed option)", "",
              "| Field | Decisions | κ | Same set |", "|---|---|---|---|"]
    pooled_l = []
    for f, opts in LISTS.items():
        dec, same = [], 0
        for s, v in by_field[f]:
            a, b = items(f, v["verified_value"]), items(f, s["your_value"])
            dec += [(o in a, o in b) for o in opts]
            same += a == b
            if a != b:
                disagree.append((f, s, v, "list"))
        pooled_l += dec  # plain yes/no decisions, so pooling does not deflate chance agreement
        lines.append(f"| {f} | {len(dec)} | {kappa(dec):.2f} | {same}/{len(by_field[f])} |")
    lines += [f"| **pooled** | {len(pooled_l)} | **{kappa(pooled_l):.2f}** | |", "",
              "## Free-text fields (no κ; same-meaning judgement needed)", "",
              "| Field | Identical after normalising | To judge |", "|---|---|---|"]
    for f in FREE:
        ident = sum(clean(s["your_value"]) == clean(v["verified_value"]) for s, v in by_field[f])
        lines.append(f"| {f} | {ident}/{len(by_field[f])} | {len(by_field[f]) - ident} |")
        disagree += [(f, s, v, "free_text") for s, v in by_field[f]
                     if clean(s["your_value"]) != clean(v["verified_value"])]
    lines += ["", "Caveats: 14 papers, so per-field κ is unstable, and κ is undefined or misleading where "
              "one category dominates (high agreement, low κ). Report the pooled values with the agreement "
              "rates. Disagreements are adjudicated after this report, never before; see "
              "`second_coder_disagreements.csv`."]
    (D / "kappa_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    with open(D / "second_coder_disagreements.csv", "w", newline="", encoding="utf-8-sig") as fh:
        w = csv.writer(fh)
        w.writerow(["paper_id", "field", "kind", "coder1_verified", "coder2", "coder2_page", "coder2_quote",
                    "coder1_quote", "pdf", "adjudicated_value", "who_was_right", "note"])
        for f, s, v, kind in sorted(disagree, key=lambda x: (x[1]["paper_id"], x[0])):
            w.writerow([s["paper_id"], f, kind, clean(v["verified_value"]), s["your_value"], s["page"],
                        s["quote"], v.get("user_quote", ""), s["pdf_file"], "", "", ""])
    print("\n".join(lines))
    print(f"\n{len(disagree)} disagreements -> {D / 'second_coder_disagreements.csv'}")


if __name__ == "__main__":
    main()
