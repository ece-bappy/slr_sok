"""Compare the two judges on the checklist fields and build the human review sheet.

Usage:
  python scripts/compare_checklist.py            # agreement + todo/08_checklist_review.csv
  python scripts/compare_checklist.py --merge    # after the human review: write
                                                 # review/synthesis/checklist_extra.csv (final values)
Agreed values are final unless the human overrides them in the sheet. Disputed values need a human
value. Agreement and Cohen's kappa go to review/checklist_coding/agreement.md.
"""
import argparse
import csv
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
D = ROOT / "review" / "checklist_coding"
SHEET = ROOT / "todo" / "08_checklist_review.csv"
FINAL = ROOT / "review" / "synthesis" / "checklist_extra.csv"
FIELDS = {"tuning_data": {"validation", "test", "not_stated"}, "per_tls_version": {"yes", "no"}}


def read(p):
    with open(p, encoding="utf-8-sig", newline="") as f:
        return {r["paper_id"]: r for r in csv.DictReader(f)}


def kappa(pairs):
    n = len(pairs)
    po = sum(a == b for a, b in pairs) / n
    ca, cb = Counter(a for a, _ in pairs), Counter(b for _, b in pairs)
    pe = sum(ca[k] * cb[k] for k in set(ca) | set(cb)) / n / n
    return (po - pe) / (1 - pe) if pe < 1 else 1.0


def build():
    fl, ag = read(D / "flash_lite.csv"), read(D / "agy.csv")
    ids = sorted(set(fl) & set(ag))
    missing = sorted((set(fl) | set(ag)) ^ set(ids))
    lines = ["# Checklist fields: judge agreement (generated by `scripts/compare_checklist.py`)", "",
             f"Papers coded by both judges: {len(ids)}. Missing from one judge: {missing or 'none'}.", "",
             "| Field | Agreement | Cohen's kappa |", "|---|---|---|"]
    rows = []
    for f in FIELDS:
        pairs = [(fl[i][f], ag[i][f]) for i in ids]
        lines.append(f"| {f} | {sum(a == b for a, b in pairs)}/{len(pairs)} | {kappa(pairs):.2f} |")
        for i in ids:
            a, b = fl[i][f], ag[i][f]
            rows.append({"paper_id": i, "field": f, "status": "agreed" if a == b else "DISPUTED",
                         "flash_lite": a, "gemini38": b,
                         "flash_lite_evidence": fl[i][f + "_evidence"], "gemini38_evidence": ag[i][f + "_evidence"],
                         "quotes_verified": f"{fl[i][f + '_quote_found']}/{ag[i][f + '_quote_found']}",
                         "pdf": f"papers/core/{i}.pdf", "your_value": "", "your_note": ""})
    (D / "agreement.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    rows.sort(key=lambda r: (r["status"] != "DISPUTED", r["field"], r["paper_id"]))
    with open(SHEET, "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    print("\n".join(lines))
    print(f"{sum(r['status'] == 'DISPUTED' for r in rows)} disputed rows -> {SHEET.relative_to(ROOT)}")


def merge():
    with open(SHEET, encoding="utf-8-sig", newline="") as fh:
        rows = list(csv.DictReader(fh))
    final = {}
    for r in rows:
        v = r["your_value"].strip().lower()
        if r["status"] == "DISPUTED" and not v:
            raise SystemExit(f"undecided: {r['paper_id']} {r['field']}")
        v = v or r["flash_lite"]
        if v not in FIELDS[r["field"]]:
            raise SystemExit(f"{r['paper_id']} {r['field']}: bad value {v!r}")
        src = "human" if r["your_value"].strip() else "agreed"
        final.setdefault(r["paper_id"], {"paper_id": r["paper_id"]})
        final[r["paper_id"]][r["field"]] = v
        final[r["paper_id"]][r["field"] + "_source"] = src
    cols = ["paper_id"] + [f"{f}{s}" for f in FIELDS for s in ("", "_source")]
    with open(FINAL, "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        w.writerows(sorted(final.values(), key=lambda r: r["paper_id"]))
    print(f"{len(final)} papers -> {FINAL.relative_to(ROOT)}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--merge", action="store_true")
    merge() if ap.parse_args().merge else build()
