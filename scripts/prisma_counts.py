"""PRISMA 2020 flow counts for the review, computed from the screening files (no hand-typed numbers).

Usage: python scripts/prisma_counts.py      -> writes review/PRISMA.md

Stages:
  identification  review/search/search_log.json (records per source, after dedup)
  screening       review/screening_llm/combined_suggestions.csv (suggested_bucket):
                    D_gemma_exclude  lenient LLM pre-screen excluded (title/abstract)
                    E_low_venue      venue-quality rule (low_venue) on pre-screen survivors
                    C_strict_exclude strict LLM pass excluded, by criterion
                    A_both_include / B_check -> human final screening
                  review/final_screening/spot_check_120.csv: human check of LLM exclusions
  eligibility     review/final_screening/final_screening_325.xlsx (human final_decision; rows whose
                  my_note starts "full-text re-check" were excluded after reading the full text)
  core set        review/ranks/core_ranks.csv (rule_A_strict) and the coded verification sheet
"""
import csv
import json
from collections import Counter
from pathlib import Path

from openpyxl import load_workbook

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "review"


def read(p):
    with open(p, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def main():
    log = json.loads((R / "search" / "search_log.json").read_text(encoding="utf-8"))
    per_src = log["records_retrieved"]
    total, dedup = per_src["total"], log["records_after_dedup"]

    cs = read(R / "screening_llm" / "combined_suggestions.csv")
    assert len(cs) == dedup, (len(cs), dedup)
    b = Counter(r["suggested_bucket"] for r in cs)
    strict_crit = Counter(r["gemini_criterion"] for r in cs if r["suggested_bucket"] == "C_strict_exclude")
    spot = read(R / "final_screening" / "spot_check_120.csv")
    spot_b = Counter(r["bucket"] for r in spot)
    spot_ok = sum(r["decision"] == "exclude" for r in spot)

    ws = load_workbook(R / "final_screening" / "final_screening_325.xlsx", read_only=True)["Screening"]
    rows = list(ws.iter_rows(values_only=True))
    rows = [dict(zip(rows[0], r)) for r in rows[1:] if r[2]]
    assert len(rows) == b["A_both_include"] + b["B_check"]
    assert all(r["final_decision"] in ("include", "exclude") for r in rows), "undecided rows"
    inc = [r for r in rows if r["final_decision"] == "include"]
    exc = [r for r in rows if r["final_decision"] == "exclude"]
    ft = [r for r in exc if str(r["my_note"] or "").lower().startswith("full-text re-check")]
    ta = [r for r in exc if r not in ft]
    ta_c, ft_c = Counter(r["exclusion_criterion"] for r in ta), Counter(r["exclusion_criterion"] for r in ft)

    ranks = read(R / "ranks" / "core_ranks.csv")
    core = [r for r in ranks if r["rule_A_strict"] == "yes"]
    coded = {r["paper_id"] for r in read(R / "coding" / "core_67_papers_verification.csv")}
    assert {r["id"] for r in core} == coded, "core rule and coded set differ"
    dl = read(R / "fulltext" / "download_list.csv")

    screened_out = b["D_gemma_exclude"] + b["E_low_venue"] + b["C_strict_exclude"]
    fmt = lambda c: ", ".join(f"{k} {v}" for k, v in c.most_common())
    L = [
        "# PRISMA 2020 flow (generated by `scripts/prisma_counts.py`; do not edit by hand)", "",
        f"Search run {log['run_timestamp_utc'][:10]}, publication years 2019-2026.", "",
        "## Identification",
        f"- Records identified: **{total:,}** (OpenAlex {per_src['openalex']:,}; Semantic Scholar "
        f"{per_src['semanticscholar']:,}; arXiv {per_src['arxiv']:,}).",
        f"- Duplicates removed: **{total - dedup:,}**.",
        "", "## Screening (title and abstract)",
        f"- Records screened: **{dedup:,}**.",
        f"- Excluded: **{screened_out:,}**",
        f"  - lenient LLM pre-screen (Gemma 4 26B, all records): {b['D_gemma_exclude']:,}",
        f"  - venue-quality rule (low_venue, not DBLP / OpenAlex-core indexed): {b['E_low_venue']:,}",
        f"  - strict LLM pass (Gemini 3.1 Flash Lite, pre-screen survivors): {b['C_strict_exclude']:,} "
        f"({fmt(strict_crit)})",
        f"- Human check of LLM exclusions: {len(spot)} random records ({fmt(spot_b)}); "
        f"{spot_ok}/{len(spot)} exclusions confirmed (miss rate 0/{len(spot)}, 95% upper bound "
        f"{3 / len(spot):.1%} by the rule of three)." if spot_ok == len(spot) else
        f"- Human check of LLM exclusions: {spot_ok}/{len(spot)} confirmed.",
        "", "## Eligibility (human, every record)",
        f"- Records assessed by a human: **{len(rows)}** (both LLM passes include: {b['A_both_include']}; "
        f"LLM disagreement or uncertainty: {b['B_check']}).",
        f"- Excluded on title/abstract or the paper's dataset section: **{len(ta)}** ({fmt(ta_c)}).",
        f"- Excluded after reading the full text (re-check of core candidates): **{len(ft)}** ({fmt(ft_c)}).",
        "", "## Included",
        f"- Studies included in the review (systematic map): **{len(inc)}**.",
        f"- Core set for full-text coding: **{len(core)}** = included studies that meet the venue rule "
        f"(CORE 2023 A*/A, or SJR Q1 in a Computer Science category, or top 10% cited in their year). "
        f"Candidates came from a provisional rank screen of all included studies ({len(dl)} candidates; "
        f"{len(dl) - len(ft) - len(ranks)} dropped before ranking, {len(ft)} excluded at full text, "
        f"{len(ranks)} ranked with the official lists, {len(core)} met the rule).",
        "", "## Reports not retrieved", "- 0 for the core set (all core PDFs obtained).", "",
    ]
    (R / "PRISMA.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
